func dateDMY(t time.Time, m [12]string) string {
	return fmt.Sprintf("%d %s %d", t.Day(), m[t.Month()-1], t.Year())
}

func dateDotDMY(t time.Time, m [12]string) string {
	return fmt.Sprintf("%d. %s %d", t.Day(), m[t.Month()-1], t.Year())
}

func dateDeMonthDe(t time.Time, m [12]string) string {
	return fmt.Sprintf("%d de %s de %d", t.Day(), m[t.Month()-1], t.Year())
}

func dateCJK(t time.Time, m [12]string) string {
	return fmt.Sprintf("%d年%s%d日", t.Year(), m[t.Month()-1], t.Day())
}

